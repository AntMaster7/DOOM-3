# Stage 9 (GL-free game path): generates neo\sys\win32\win_qgl_null.inl from QGL_Init in
# win_qgl.cpp: QGL_InitNull() points every qgl / qwgl entry at a counted no-op, so that a stray
# OpenGL call in r_swRenderer 2 is a line in a report instead of a crash.
#   python tools\port-x64\gen_qgl_null.py        (re-run when QGL_Init gains an entry point)
import os, re

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..', 'neo', 'sys', 'win32'))
src = open(os.path.join(ROOT, 'win_qgl.cpp'), encoding='latin-1').read()
body = src[src.index('bool QGL_Init( const char *dllname )'):]
body = body[:body.index('return true;')]

# some entries carry a cast: qglGetError = dllGetError = ( GLenum (__stdcall * )(void) ) glGetError;
gl = re.findall(r'^\s*(qgl\w+)\s*=\s*(dll\w+)\s*=\s*(?:\([^;]*\)\s*)?(gl\w+)\s*;', body, re.M)
wgl = re.findall(r'^\s*(qwgl\w+)\s*=\s*(\w+);', body, re.M)
# the check: every pointer QGL_Shutdown nulls must be bound here (one missed entry is a call through NULL)
shut = src[src.index('void QGL_Shutdown( void )'):src.index('bool QGL_Init( const char *dllname )')]
nulled = set(re.findall(r'^\s*(qw?gl\w+)\s*=\s*NULL;', shut, re.M))
bound = {q for q, _, _ in gl} | {q for q, _ in wgl}
assert not (nulled - bound), sorted(nulled - bound)

# entry points with an answer the engine depends on: written by hand below, not counted as stray
SPECIAL = {'glGetString', 'glGetIntegerv', 'glGenTextures', 'wglGetProcAddress'}

STUBS = 640     # core + WGL entries plus every extension pointer R_CheckPortableExtensions asks for
out = []
w = out.append
w('/* GENERATED by tools\\port-x64\\gen_qgl_null.py from QGL_Init: do not edit.')
w('   r_swRenderer 2: no opengl32.dll. Every qgl / qwgl pointer is a no-op that counts its calls;')
w('   QGL_NullReport lists them. One stub per entry point, handed out by name, so an extension')
w('   pointer asked for at run time (GLimp_ExtensionPointer) gets one as well.')
w('   The stub takes no arguments and returns 0 in RAX: valid for every GL signature under the x64')
w('   calling convention (arguments in registers or caller-cleaned stack). x64 only, as is the mode. */')
w('')
w('#define QGL_NULL_STUBS %d' % STUBS)
w('static int			qglNullCalls[QGL_NULL_STUBS];')
w('static const char *	qglNullNames[QGL_NULL_STUBS];')
w('static int			qglNullCount;')
w('')
w('template< int N > static intptr_t APIENTRY QGL_NullStub( void ) { qglNullCalls[N]++; return 0; }')
w('#define QGL_S8( b ) (void *)&QGL_NullStub< b >, (void *)&QGL_NullStub< b + 1 >, (void *)&QGL_NullStub< b + 2 >, (void *)&QGL_NullStub< b + 3 >, \\')
w('	(void *)&QGL_NullStub< b + 4 >, (void *)&QGL_NullStub< b + 5 >, (void *)&QGL_NullStub< b + 6 >, (void *)&QGL_NullStub< b + 7 >')
w('#define QGL_S64( b ) QGL_S8( b ), QGL_S8( b + 8 ), QGL_S8( b + 16 ), QGL_S8( b + 24 ), QGL_S8( b + 32 ), QGL_S8( b + 40 ), QGL_S8( b + 48 ), QGL_S8( b + 56 )')
w('static void * const qglNullStubs[QGL_NULL_STUBS] = {')
w('	' + ', '.join('QGL_S64( %d )' % b for b in range(0, STUBS, 64)))
w('};')
w('')
w('static void *QGL_NullProc( const char *name ) {')
w('	for ( int i = 0; i < qglNullCount; i++ ) {')
w('		if ( !strcmp( qglNullNames[i], name ) ) {')
w('			return qglNullStubs[i];')
w('		}')
w('	}')
w('	if ( qglNullCount == QGL_NULL_STUBS - 1 ) {')
w('		qglNullNames[qglNullCount] = "(more entry points than stubs)";')
w('		return qglNullStubs[qglNullCount];')
w('	}')
w('	qglNullNames[qglNullCount] = Mem_CopyString( name );		// extension names come from the caller\'s stack or literals: keep a copy')
w('	return qglNullStubs[qglNullCount++];')
w('}')
w('')
w('// ---- the entry points whose answer the engine depends on')
w('')
w('static const GLubyte * APIENTRY QGL_NullGetString( GLenum name ) {')
w('	switch ( name ) {')
w('	case GL_VENDOR:		return (const GLubyte *)"DOOM 3 software renderer";')
w('	case GL_RENDERER:	return (const GLubyte *)"AVX-512 tile rasterizer (no OpenGL)";')
w('	case GL_VERSION:	return (const GLubyte *)"1.5 none";')
w('	// what the ARB2 path and the software back end rely on, and nothing else: no texture compression')
w('	// (the CPU twins want RGBA), no vertex buffer objects (the vertex cache stays in CPU memory)')
w('	case GL_EXTENSIONS:	return (const GLubyte *)"GL_ARB_multitexture GL_ARB_texture_env_combine GL_ARB_texture_cube_map "')
w('							"GL_ARB_texture_env_dot3 GL_ARB_texture_env_add GL_ARB_texture_non_power_of_two GL_EXT_stencil_wrap "')
w('							"GL_EXT_stencil_two_side GL_ARB_vertex_program GL_ARB_fragment_program GL_EXT_depth_bounds_test";')
w('	}')
w('	return (const GLubyte *)"";')
w('}')
w('')
w('static void APIENTRY QGL_NullGetIntegerv( GLenum pname, GLint *params ) {')
w('	switch ( pname ) {')
w('	case GL_MAX_TEXTURE_SIZE:				*params = 8192; break;')
w('	case GL_MAX_TEXTURE_UNITS_ARB:			*params = 8; break;')
w('	case GL_MAX_TEXTURE_COORDS_ARB:			*params = 8; break;')
w('	case GL_MAX_TEXTURE_IMAGE_UNITS_ARB:	*params = 8; break;')
w('	case GL_PROGRAM_ERROR_POSITION_ARB:		*params = -1; break;	// "the program compiled"')
w('	default:								*params = 0; break;')
w('	}')
w('}')
w('')
w('static void APIENTRY QGL_NullGenTextures( GLsizei n, GLuint *textures ) {')
w('	static GLuint next = 1024;		// idImage tells "loaded" from its texnum')
w('	for ( GLsizei i = 0; i < n; i++ ) {')
w('		textures[i] = next++;')
w('	}')
w('}')
w('')
w('static PROC WINAPI QGL_NullGetProcAddress( LPCSTR name ) {')
w('	return (PROC)QGL_NullProc( name );')
w('}')
w('')
w('bool QGL_InitNull( void ) {')
w('	assert( win32.hinstOpenGL == 0 );')
w('	common->Printf( "...no OpenGL: every qgl entry point is a counted no-op\\n" );')
w('')
for q, d, g in gl:
    if g in SPECIAL:
        continue
    w('	%s = %s = ( decltype( %s ) )QGL_NullProc( "%s" );' % (q, d, d, g))
w('')
for q, g in wgl:
    name = g[:-1] if g in ('wglUseFontBitmapsA', 'wglUseFontOutlinesA') else g
    if name in SPECIAL:
        continue
    w('	%s = ( decltype( %s ) )QGL_NullProc( "%s" );' % (q, q, name))
w('')
w('	qglGetString = dllGetString = QGL_NullGetString;')
w('	qglGetIntegerv = dllGetIntegerv = QGL_NullGetIntegerv;')
w('	qglGenTextures = dllGenTextures = QGL_NullGenTextures;')
w('	qwglGetProcAddress = QGL_NullGetProcAddress;')
w('')
w('	qglActiveTextureARB = 0;')
w('	qglClientActiveTextureARB = 0;')
w('	qglMultiTexCoord2fARB = 0;')
w('	return true;')
w('}')
w('')
w('/* The stray-call report. Stage 9 is done when it is empty and opengl32.dll is not in the process. */')
w('void QGL_NullReport( bool all ) {')
w('	int total = 0, entries = 0;')
w('	for ( int i = 0; i < qglNullCount; i++ ) {')
w('		if ( qglNullCalls[i] ) {')
w('			total += qglNullCalls[i];')
w('			entries++;')
w('		}')
w('	}')
w('	common->Printf( "stray OpenGL calls: %i through %i entry points; opengl32.dll is %s\\n", total, entries,')
w('		GetModuleHandle( "opengl32.dll" ) ? "LOADED" : "not loaded" );')
w('	// most calls first')
w('	for ( int printed = 0; printed < ( all ? entries : Min( entries, 40 ) ); printed++ ) {')
w('		int best = -1;')
w('		for ( int i = 0; i < qglNullCount; i++ ) {')
w('			if ( qglNullCalls[i] > 0 && ( best < 0 || qglNullCalls[i] > qglNullCalls[best] ) ) {')
w('				best = i;')
w('			}')
w('		}')
w('		if ( best < 0 ) {')
w('			break;')
w('		}')
w('		common->Printf( "  %9i  %s\\n", qglNullCalls[best], qglNullNames[best] );')
w('		qglNullCalls[best] = -qglNullCalls[best];		// printed')
w('	}')
w('	for ( int i = 0; i < qglNullCount; i++ ) {')
w('		if ( qglNullCalls[i] < 0 ) {')
w('			qglNullCalls[i] = -qglNullCalls[i];')
w('		}')
w('	}')
w('}')
w('')

path = os.path.join(ROOT, 'win_qgl_null.inl')
open(path, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out))
print('wrote', path, ':', len(gl), 'gl +', len(wgl), 'wgl entry points')
